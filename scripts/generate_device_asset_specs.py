#!/usr/bin/env python3
"""Generate firmware cache allowlist from the canonical shared manifest."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def generate(root: Path = ROOT) -> None:
    manifest = json.loads((root / "shared/asset-manifest.json").read_text())
    selected = [(key, value) for key, value in manifest["assets"].items()
            if key in {"background-flower", "background-chevron", "background-mechanical-flower", "background-black-white-circle"}]
    if len(selected) != 4:
        raise SystemExit("Expected the four canonical selected Home/Clock wallpapers")
    lines = ["// Generated by scripts/generate_device_asset_specs.py; do not edit.",
         "#pragma once", "#include \"persistent_asset_cache.h\"", "namespace leopold::asset_cache {",
         f"inline constexpr uint32_t kCatalogVersion = {manifest.get('catalog_version', 1)}u;",
         f"inline constexpr uint32_t kRendererCompatibility = {manifest.get('renderer_compatibility', 1)}u;"]
    lines.append("inline constexpr AssetSpec kSelectedWallpapers[] = {")
    for key, item in selected:
        asset_path = root / "shared/assets" / item["file"]
        payload = asset_path.read_bytes()
        digest = hashlib.sha256(payload).hexdigest()
        values = (key, item["file"], item.get("bytes", len(payload)), item.get("sha256", digest), item["width"], item["height"])
        lines.append('  {"%s", "%s", %du, "%s", %du, %du},' % values)
    lines += ["};", "}  // namespace leopold::asset_cache", ""]
    target = root / "device/include/generated_selected_asset_specs.h"
    result = "\n".join(lines)
    if target.exists() and target.read_text() == result:
        print("Selected device asset specs are synchronized")
    else:
        target.write_text(result)
        print(f"Generated {target.relative_to(root)} from shared/asset-manifest.json")

if __name__ == "__main__":
    generate()
